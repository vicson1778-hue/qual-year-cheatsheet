// Стоимость одного применения. p: товар с рассчитанной ценой (p.price в рублях), d: его описание,
// byId: словарь товаров (нужен для ссылок ref на другой товар, например картридж для воды).
// Возвращает список вариантов: { short, calc, note, value }.
window.SHOP_PERUSE = function (p, d, byId) {
  var list = d && d.perUse ? [].concat(d.perUse) : [];
  var num = function (v, dec) {
    return new Intl.NumberFormat("ru-RU", { minimumFractionDigits: dec, maximumFractionDigits: dec }).format(v);
  };
  return list.map(function (u) {
    var base = u.ref && byId && byId[u.ref] ? byId[u.ref].price : p.price;
    var v = base / u.n;
    var dec = u.dec != null ? u.dec : (v >= 100 ? 0 : 1);
    var val = num(v, dec);
    return {
      value: v,
      short: "≈ " + val + " ₽ за " + u.unit,
      calc: num(base, 0) + " ₽ ÷ " + num(u.n, u.n % 1 ? 1 : 0) + " = " + val + " ₽",
      note: u.note + (u.assumed ? " (расчётная норма)" : "")
    };
  });
};
